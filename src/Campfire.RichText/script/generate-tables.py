#!/usr/bin/env python3
"""Generates Unicode/WordRanges.fs.

  script/generate-tables.py WORD_RANGES_TXT

WORD_RANGES_TXT is "lo hi" hex lines, one per
range of code points the Rust regex crate's `\\w` matches (script/word-ranges.rs prints it).
"""
import re
import sys

word_txt = sys.argv[1]

ranges = [tuple(int(x, 16) for x in line.split()) for line in open(word_txt) if line.strip()]
with open("Unicode/WordRanges.fs", "w") as out:
    out.write("// Generated by script/generate-tables.py: the code points the Rust regex crate (1.13.1) matches\n")
    out.write("// with `\\w` (Unicode's Alphabetic, Mark, Decimal_Number, Connector_Punctuation and Join_Control).\n")
    out.write("module internal Campfire.RichText.Unicode.WordRanges\n\n")
    out.write(f"/// {len(ranges)} inclusive ranges, ascending, as lo0 hi0 lo1 hi1 ...\n")
    out.write("let ranges : int[] =\n    [|\n")
    flat = []
    for lo, hi in ranges:
        flat += [lo, hi]
    for i in range(0, len(flat), 8):
        out.write("        " + "; ".join(f"0x{v:x}" for v in flat[i:i+8]) + ";\n")
    out.write("    |]\n")
